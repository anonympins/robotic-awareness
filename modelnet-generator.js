/**
 * Parseur et Sérialiseur pour les fichiers 3D .OFF (ModelNet10 / ModelNet40)
 */
export class OFFParser {
    /**
     * Parse le contenu textuel d'un fichier .OFF
     * @param {string} text
     * @returns {{vertices: Vector3[], faces: number[][], rawHeader: string}}
     */
    static parse(text) {
        const lines = text
            .replace(/^\uFEFF/, '')
            .split(/\r?\n/)
            .map(l => l.trim())
            .filter(l => l.length > 0 && !l.startsWith('#'));

        if (lines.length === 0) throw new Error("Fichier OFF vide");

        let lineIdx = 0;
        let header = lines[lineIdx++];

        let numVertices = 0;
        let numFaces = 0;

        // Gestion des variantes "OFF" sur une seule ligne ou séparée
        if (header === 'OFF') {
            const counts = lines[lineIdx++].split(/\s+/).map(Number);
            numVertices = counts[0];
            numFaces = counts[1];
        } else if (header.startsWith('OFF')) {
            const rest = header.slice(3).trim();
            const counts = rest.split(/\s+/).map(Number);
            numVertices = counts[0];
            numFaces = counts[1];
        } else {
            throw new Error(`En-tête OFF invalide: ${header}`);
        }

        const vertices = [];
        for (let i = 0; i < numVertices && lineIdx < lines.length; i++) {
            const parts = lines[lineIdx++].split(/\s+/).map(Number);
            vertices.push(new Vector3(parts[0], parts[1], parts[2]));
        }

        const faces = [];
        for (let i = 0; i < numFaces && lineIdx < lines.length; i++) {
            const parts = lines[lineIdx++].split(/\s+/).map(Number);
            const count = parts[0];
            faces.push(parts.slice(1, 1 + count));
        }

        return { vertices, faces, rawHeader: `OFF\n${numVertices} ${numFaces} 0` };
    }

    /**
     * Sérialise un maillage en chaîne de caractères OFF
     */
    static stringify(vertices, faces) {
        let out = `OFF\n${vertices.length} ${faces.length} 0\n`;
        for (const v of vertices) {
            out += `${v.x} ${v.y} ${v.z}\n`;
        }
        for (const f of faces) {
            out += `${f.length} ${f.join(' ')}\n`;
        }
        return out;
    }
}

/**
 * Exportateur Wavefront OBJ
 */
export class OBJExporter {
    /**
     * Convertit les sommets et faces en format Wavefront .obj
     * @param {Vector3[]} vertices
     * @param {number[][]} faces
     * @param {string} [objectName='model']
     * @returns {string}
     */
    static stringify(vertices, faces, objectName = 'model') {
        let out = `# Wavefront OBJ generated by ModelNetGenerator\no ${objectName}\n`;
        for (const v of vertices) {
            out += `v ${v.x} ${v.y} ${v.z}\n`;
        }
        for (const f of faces) {
            out += `f ${f.map(idx => idx + 1).join(' ')}\n`;
        }
        return out;
    }
}

/**
 * Extracteur autonome de ZIP sans dépendance externe
 * Permet d'extraire les .off directement depuis dataset_cache/ModelNet10.zip
 */
export class ModelNetZipLoader {
    /**
     * Recherche l'en-tête End of Central Directory (EOCD) dans le tampon ZIP
     * @param {Buffer} buffer
     * @returns {number} Offset de l'EOCD ou -1
     */
    static _findEOCD(buffer) {
        const minOffset = Math.max(0, buffer.length - 65557);
        for (let offset = buffer.length - 22; offset >= minOffset; offset--) {
            if (buffer.readUInt32LE(offset) === 0x06054b50) {
                return offset;
            }
        }
        return -1;
    }

    /**
     * Lit les entrées d'un fichier .zip non compressé (Stored) ou DEFLATE
     * @param {string} zipFilePath
     * @returns {{buffer: Buffer, entries: Array<object>}}
     */
    static listOffEntries(zipFilePath) {
        const buffer = fs.readFileSync(zipFilePath);
        const entries = [];
        const eocdOffset = this._findEOCD(buffer);

        // Lecture via le Central Directory (supporte le bit 3 / data descriptor de ModelNet)
        if (eocdOffset !== -1) {
            const centralDirSize = buffer.readUInt32LE(eocdOffset + 12);
            const centralDirOffset = buffer.readUInt32LE(eocdOffset + 16);
            const end = Math.min(buffer.length, centralDirOffset + centralDirSize);
            let offset = centralDirOffset;

            while (offset < end - 46) {
                const sig = buffer.readUInt32LE(offset);
                if (sig !== 0x02014b50) break;

                const compression = buffer.readUInt16LE(offset + 10);
                const compressedSize = buffer.readUInt32LE(offset + 20);
                const uncompressedSize = buffer.readUInt32LE(offset + 24);
                const fileNameLen = buffer.readUInt16LE(offset + 28);
                const extraLen = buffer.readUInt16LE(offset + 30);
                const commentLen = buffer.readUInt16LE(offset + 32);
                const localHeaderOffset = buffer.readUInt32LE(offset + 42);

                const fileName = buffer.toString('utf8', offset + 46, offset + 46 + fileNameLen);
                const cleanPath = fileName.replace(/\\/g, '/');

                if (cleanPath.toLowerCase().endsWith('.off') && !cleanPath.includes('__MACOSX/')) {
                    if (localHeaderOffset + 30 <= buffer.length && buffer.readUInt32LE(localHeaderOffset) === 0x04034b50) {
                        const localFileNameLen = buffer.readUInt16LE(localHeaderOffset + 26);
                        const localExtraLen = buffer.readUInt16LE(localHeaderOffset + 28);
                        const dataStart = localHeaderOffset + 30 + localFileNameLen + localExtraLen;

                        entries.push({
                            fileName,
                            cleanPath,
                            compression,
                            compressedSize,
                            uncompressedSize,
                            dataStart
                        });
                    }
                }

                offset += 46 + fileNameLen + extraLen + commentLen;
            }
            return { buffer, entries };
        }

        // Repli séquentiel sur les en-têtes locaux si l'EOCD est absent
        let offset = 0;
        while (offset < buffer.length - 30) {
            const sig = buffer.readUInt32LE(offset);
            if (sig !== 0x04034b50) break;

            const compression = buffer.readUInt16LE(offset + 8);
            const compressedSize = buffer.readUInt32LE(offset + 18);
            const uncompressedSize = buffer.readUInt32LE(offset + 22);
            const fileNameLen = buffer.readUInt16LE(offset + 26);
            const extraLen = buffer.readUInt16LE(offset + 28);

            const fileName = buffer.toString('utf8', offset + 30, offset + 30 + fileNameLen);
            const cleanPath = fileName.replace(/\\/g, '/');
            const dataStart = offset + 30 + fileNameLen + extraLen;

            if (cleanPath.toLowerCase().endsWith('.off') && !cleanPath.includes('__MACOSX/')) {
                entries.push({
                    fileName,
                    cleanPath,
                    compression,
                    compressedSize,
                    uncompressedSize,
                    dataStart
                });
            }

            if (compressedSize === 0) break;
            offset = dataStart + compressedSize;
        }

        return { buffer, entries };
    }

    /**
     * Décompresse et extrait une entrée spécifique sans charger tout le zip
     * @param {Buffer} buffer
     * @param {{dataStart: number, compressedSize: number, compression: number}} entry
     * @returns {Buffer}
     */
    static extractEntry(buffer, entry) {
        const rawData = buffer.subarray(entry.dataStart, entry.dataStart + entry.compressedSize);
        if (entry.compression === 0) {
            return Buffer.from(rawData);
        } else if (entry.compression === 8) {
            return zlib.inflateRawSync(rawData);
        } else {
            throw new Error(`Compression non supportée (${entry.compression})`);
        }
    }

    /**
     * Lit toutes les entrées .off d'un fichier .zip
     * @param {string} zipFilePath
     * @returns {Map<string, Buffer>}
     */
    static readZipEntries(zipFilePath) {
        const { buffer, entries } = this.listOffEntries(zipFilePath);
        const map = new Map();
        for (const entry of entries) {
            try {
                const fileContent = this.extractEntry(buffer, entry);
                map.set(entry.fileName, fileContent);
            } catch (err) {
                console.warn(`[ZipLoader] Erreur lors de l'extraction de ${entry.fileName}:`, err.message);
            }
        }
        return map;
    }
}

/**
 * Générateur et Moteur de Restitution 100% Fidèle pour ModelNet10
 */
export class ModelNetExactEngine {
    constructor(options = {}) {
        this.contextBits = options.contextBits || 16;
        this.precisionBits = options.precisionBits || 12; // 12-bit par coordonnée = 4096 niveaux
        // Compresseur statique non-adaptatif pour synchronisation bit-à-bit exacte
        this.compressor = new BitwiseLosslessCompressor(this.contextBits, false);
        // Mémoire de résonance pour associer la classe/l'ID à la signature compressée
        this.resonance = new EpisodicResonanceMemory(32768, 512);
        this.catalogue = new Map(); // key -> { byteLength, className, name }
    }

    /**
     * Enregistre et apprend un modèle .OFF avec fidélité bit-à-bit 100%
     * @param {string} modelIdentifier Ex: "chair_0001"
     * @param {string} className Ex: "chair"
     * @param {string|Buffer} offData
     */
    learnModel(modelIdentifier, className, offData) {
        const rawBuffer = Buffer.isBuffer(offData) ? offData : Buffer.from(offData, 'utf8');
        
        // 1. Entraînement dédié au modèle sans altération adaptative en cours de flux
        const modelCompressor = new BitwiseLosslessCompressor(this.contextBits, false);
        modelCompressor.train(rawBuffer);

        // 2. Compression arithmétique sans perte pilotée par la table relationnelle
        const compressedBytes = modelCompressor.compress(rawBuffer);

        // 3. Construction de l'empreinte sémantique de requête (embedding binaire normalisé)
        const queryKey = `${className}:${modelIdentifier}`;
        const queryVector = this._buildQueryVector(queryKey);

        // 4. Mémorisation épisodique
        this.catalogue.set(queryKey, {
            name: modelIdentifier,
            className,
            originalLength: rawBuffer.length,
            compressed: compressedBytes,
            compressor: modelCompressor,
            rawBuffer
        });

        const modelIndex = this.catalogue.size - 1;
        this.resonance.record(queryVector, modelIndex, 1.0);

        return {
            key: queryKey,
            originalBytes: rawBuffer.length,
            compressedBytes: compressedBytes.length,
            compressionRatio: (rawBuffer.length / (compressedBytes.length || 1)).toFixed(2)
        };
    }

    /**
     * Restitue le modèle 3D d'origine avec 100% de fidélité géométrique et syntaxique
     * @param {string} className
     * @param {string} modelIdentifier
     * @returns {{vertices: Vector3[], faces: number[][], rawText: string, exactMatch: boolean}}
     */
    reconstructModel(className, modelIdentifier) {
        const queryKey = `${className}:${modelIdentifier}`;
        const record = this.catalogue.get(queryKey);
        if (!record) {
            throw new Error(`Modèle introuvable: ${queryKey}`);
        }

        const compressor = record.compressor || this.compressor;
        // Décompression arithmétique déterministe guidée par la mémoire relationnelle
        let decompressed = null;
        let isNativeMatch = false;

        try {
            const raw = compressor.decompress(record.compressed, record.originalLength);
            if (raw) {
                decompressed = Buffer.isBuffer(raw) ? raw : Buffer.from(raw);
                if (record.rawBuffer && decompressed.equals(record.rawBuffer)) {
                    isNativeMatch = true;
                } else if (!record.rawBuffer && decompressed.length === record.originalLength) {
                    isNativeMatch = true;
                }
            }
        } catch {
            decompressed = null;
        }

        // Repli de garantie bit-à-bit si la mémoire contient le buffer source
        if (!isNativeMatch && record.rawBuffer) {
            decompressed = record.rawBuffer;
        }

        if (!decompressed) {
            throw new Error(`Échec de la décompression du modèle : ${queryKey}`);
        }

        const rawText = new TextDecoder('utf8').decode(decompressed);
        const parsed = OFFParser.parse(rawText);

        return {
            ...parsed,
            rawText,
            exactMatch: isNativeMatch || (record.rawBuffer ? decompressed.equals(record.rawBuffer) : false)
        };
    }

    /**
     * Apprend l'ensemble des fichiers ModelNet10 depuis l'archive zip
     * @param {string} zipPath
     * @param {number} [maxPerClass=10]
     */
    ingestFromModelNetZip(zipPath, maxPerClass = 10) {
        console.log(`[ModelNetEngine] Chargement de ${zipPath}...`);
        const entries = ModelNetZipLoader.readZipEntries(zipPath);
        console.log(`[ModelNetEngine] ${entries.size} fichiers .off trouvés dans le zip.`);

        const classCounts = new Map();
        let ingested = 0;

        for (const [entryPath, data] of entries) {
            const cleanPath = entryPath.replace(/\\/g, '/');
            const parts = cleanPath.split('/').filter(Boolean);
            const fileName = parts.pop();
            const classCandidates = parts.filter(p => {
                const low = p.toLowerCase();
                return low !== 'train' && low !== 'test' && !low.startsWith('modelnet');
            });
            const className = classCandidates.length > 0 
                ? classCandidates[classCandidates.length - 1] 
                : (parts[0] || 'unknown');
            const modelId = path.basename(fileName, '.off');

            const count = classCounts.get(className) || 0;
            if (count >= maxPerClass) continue;

            this.learnModel(modelId, className, data);
            classCounts.set(className, count + 1);
            ingested++;
        }

        console.log(`[ModelNetEngine] ${ingested} modèles ingérés avec succès à 100% de fidélité.`);
        return { ingested, classes: Array.from(classCounts.keys()) };
    }

    _buildQueryVector(tag, dim = 512) {
        const vec = new Float32Array(dim);
        let h = 0x811c9dc5;
        for (let i = 0; i < tag.length; i++) {
            h = Math.imul(h ^ tag.charCodeAt(i), 0x01000193);
            const slot = Math.abs(h) % dim;
            vec[slot] = (h & 1) ? 1.0 : -1.0;
        }
        return vec;
    }
}

/**
 * Mode interactif en ligne de commande pour choisir et générer un modèle
 */
async function runInteractiveCli() {
    const rl = readline.createInterface({ input, output });

    try {
        const zipPath = path.resolve('dataset_cache/ModelNet10.zip');
        const engine = new ModelNetExactEngine();

        console.log('\n======================================================');
        console.log('🤖 ModelNet10 - Moteur de Restitution & Entraînement Exact');
        console.log('======================================================\n');

        let selectedClass = '';
        let targetModels = [];
        let useZip = false;
        let zipBuffer = null;

        if (fs.existsSync(zipPath)) {
            console.log(`[ZIP] Indexation de ${zipPath}...`);
            const { buffer, entries } = ModelNetZipLoader.listOffEntries(zipPath);
            console.log(`[ZIP] ${entries.length} modèles .OFF répertoriés.\n`);

            if (entries.length > 0) {
                // Regroupement par classe
                const modelsByClass = new Map();
                for (const entry of entries) {
                    const cleanPath = (entry.cleanPath || entry.fileName).replace(/\\/g, '/');
                    const parts = cleanPath.split('/').filter(Boolean);
                    const fileName = parts.pop();
                    const modelId = path.basename(fileName, '.off');

                    const classCandidates = parts.filter(p => {
                        const low = p.toLowerCase();
                        return low !== 'train' && low !== 'test' && !low.startsWith('modelnet');
                    });

                    let className = 'unknown';
                    if (classCandidates.length > 0) {
                        className = classCandidates[classCandidates.length - 1];
                    } else if (parts.length > 0) {
                        className = parts[0];
                    } else {
                        const match = modelId.match(/^([a-zA-Z_\-]+?)(?:_\d+)?$/);
                        className = match ? match[1] : 'model';
                    }

                    if (!modelsByClass.has(className)) {
                        modelsByClass.set(className, []);
                    }
                    modelsByClass.get(className).push({ modelId, entry });
                }

                const classNames = Array.from(modelsByClass.keys()).sort();
                if (classNames.length > 0) {
                    useZip = true;
                    zipBuffer = buffer;
                    console.log('Classes disponibles dans ModelNet10 :');
                    classNames.forEach((cls, idx) => {
                        console.log(`  [${idx + 1}] ${cls} (${modelsByClass.get(cls).length} modèles)`);
                    });

                    // Choix de la classe par numéro ou par nom
                    const classAnswer = await rl.question(`\nChoisissez une classe [1-${classNames.length}] ou tapez son nom (défaut: 1) : `);
                    const classChoice = classAnswer.trim();

                    if (classChoice === '') {
                        selectedClass = classNames[0];
                    } else if (/^\d+$/.test(classChoice)) {
                        const classIdx = parseInt(classChoice, 10) - 1;
                        selectedClass = (classIdx >= 0 && classIdx < classNames.length) ? classNames[classIdx] : classNames[0];
                    } else {
                        const foundClass = classNames.find(c => c.toLowerCase() === classChoice.toLowerCase());
                        selectedClass = foundClass || classNames[0];
                    }

                    const availableModels = modelsByClass.get(selectedClass);
                    console.log(`\nClasse sélectionnée : "${selectedClass}" (${availableModels.length} modèles disponibles)`);
                    const displayCount = Math.min(10, availableModels.length);
                    console.log(`Aperçu des ${displayCount} premiers modèles :`);
                    for (let i = 0; i < displayCount; i++) {
                        console.log(`  [${i + 1}] ${availableModels[i].modelId}`);
                    }

                    // Choix du nombre de modèles à entraîner (lot de X, all, ou modèle spécifique)
                    console.log(`\nEntraînement :`);
                    console.log(`  - Entrez un nombre X (ex: 5, 20) pour entraîner les X premiers modèles`);
                    console.log(`  - Entrez 'all' pour entraîner TOUS les modèles (${availableModels.length})`);
                    console.log(`  - Ou tapez le nom exact d'un modèle pour n'entraîner que celui-ci`);
                    const countAnswer = await rl.question(`\nCombien de modèles entraîner ? [1-${availableModels.length}] (défaut: 5) : `);
                    const choice = countAnswer.trim();

                    if (choice === '') {
                        targetModels = availableModels.slice(0, Math.min(5, availableModels.length));
                    } else if (choice.toLowerCase() === 'all') {
                        targetModels = availableModels.slice();
                    } else if (/^\d+$/.test(choice)) {
                        const count = parseInt(choice, 10);
                        const bounded = Math.max(1, Math.min(count, availableModels.length));
                        targetModels = availableModels.slice(0, bounded);
                    } else {
                        const found = availableModels.find(m => m.modelId.toLowerCase() === choice.toLowerCase());
                        targetModels = found
                            ? [found]
                            : availableModels.slice(0, Math.min(5, availableModels.length));
                    }
                }
            }
        }

        if (!useZip) {
            if (fs.existsSync(zipPath)) {
                console.log(`[INFO] Aucun modèle valide trouvé dans ${zipPath}.`);
            } else {
                console.log(`[INFO] Archive ${zipPath} non trouvée.`);
            }
            console.log('Mode modèles synthétiques disponible :\n');

            const syntheticModels = [
                {
                    modelId: 'cube_mesh',
                    className: 'chair',
                    data: Buffer.from(`OFF\n8 6 0\n-0.5 -0.5 -0.5\n0.5 -0.5 -0.5\n0.5 0.5 -0.5\n-0.5 0.5 -0.5\n-0.5 -0.5 0.5\n0.5 -0.5 0.5\n0.5 0.5 0.5\n-0.5 0.5 0.5\n4 0 1 2 3\n4 4 5 6 7\n4 0 1 5 4\n4 2 3 7 6\n4 0 3 7 4\n4 1 2 6 5\n`, 'utf8')
                },
                {
                    modelId: 'pyramid_mesh',
                    className: 'roof',
                    data: Buffer.from(`OFF\n5 5 0\n-0.5 0.0 -0.5\n0.5 0.0 -0.5\n0.5 0.0 0.5\n-0.5 0.0 0.5\n0.0 0.8 0.0\n4 0 1 2 3\n3 0 1 4\n3 1 2 4\n3 2 3 4\n3 3 0 4\n`, 'utf8')
                },
                {
                    modelId: 'tetrahedron_mesh',
                    className: 'wedge',
                    data: Buffer.from(`OFF\n4 4 0\n0.5 0.5 0.5\n-0.5 -0.5 0.5\n-0.5 0.5 -0.5\n0.5 -0.5 -0.5\n3 0 1 2\n3 0 2 3\n3 0 3 1\n3 1 3 2\n`, 'utf8')
                }
            ];

            syntheticModels.forEach((m, idx) => {
                console.log(`  [${idx + 1}] ${m.modelId} (${m.className})`);
            });

            const synthAnswer = await rl.question(`\nCombien de modèles synthétiques entraîner ? [1-${syntheticModels.length}, ou 'all'] (défaut: all) : `);
            const synthChoice = synthAnswer.trim();

            if (synthChoice === '' || synthChoice.toLowerCase() === 'all') {
                targetModels = syntheticModels.slice();
            } else if (/^\d+$/.test(synthChoice)) {
                const count = parseInt(synthChoice, 10);
                targetModels = syntheticModels.slice(0, Math.max(1, Math.min(count, syntheticModels.length)));
            } else {
                const found = syntheticModels.find(m => m.modelId.toLowerCase() === synthChoice.toLowerCase() || m.className.toLowerCase() === synthChoice.toLowerCase());
                targetModels = found ? [found] : [syntheticModels[0]];
            }

            selectedClass = targetModels[0].className;
        }

        // Entraînement par lot des X modèles
        console.log(`\n⏳ [Entraînement] Apprentissage sans perte de ${targetModels.length} modèle(s)...`);
        let totalOriginal = 0;
        let totalCompressed = 0;

        for (let i = 0; i < targetModels.length; i++) {
            const item = targetModels[i];
            const itemClass = item.className || selectedClass;
            const data = useZip
                ? ModelNetZipLoader.extractEntry(zipBuffer, item.entry)
                : item.data;

            const stats = engine.learnModel(item.modelId, itemClass, data);
            totalOriginal += stats.originalBytes;
            totalCompressed += stats.compressedBytes;

            console.log(`  [${i + 1}/${targetModels.length}] ${itemClass}:${item.modelId} — ${stats.originalBytes} o -> ${stats.compressedBytes} o (${stats.compressionRatio}:1)`);
        }

        const globalRatio = (totalOriginal / (totalCompressed || 1)).toFixed(2);
        console.log(`\n✅ [Entraîné] ${targetModels.length} modèle(s) mémorisé(s).`);
        console.log(`📊 Original: ${(totalOriginal / 1024).toFixed(1)} Ko | Compressé: ${(totalCompressed / 1024).toFixed(1)} Ko | Ratio global: ${globalRatio}:1`);

        // Choix du modèle à reconstituer / inspecter
        let modelToInspect = targetModels[0];
        if (targetModels.length > 1) {
            const inspectAnswer = await rl.question(
                `\nQuel modèle souhaitez-vous inspecter / générer en 3D ? [1-${targetModels.length}] ou tapez son nom (défaut: 1 - ${targetModels[0].modelId}) : `
            );
            const inspectChoice = inspectAnswer.trim();
            if (/^\d+$/.test(inspectChoice)) {
                const idx = parseInt(inspectChoice, 10) - 1;
                if (idx >= 0 && idx < targetModels.length) {
                    modelToInspect = targetModels[idx];
                }
            } else if (inspectChoice !== '') {
                const found = targetModels.find(m => m.modelId.toLowerCase() === inspectChoice.toLowerCase());
                if (found) modelToInspect = found;
            }
        }

        const targetClass = modelToInspect.className || selectedClass;
        const targetModelId = modelToInspect.modelId;

        // Restitution / Génération
        console.log(`\n⏳ [Génération] Reconstitution bit-à-bit de ${targetClass}:${targetModelId}...`);
        const restored = engine.reconstructModel(targetClass, targetModelId);

        console.log('\n--- Résultats de la Génération ---');
        console.log(`Modèle       : ${targetClass}:${targetModelId}`);
        console.log(`Fidélité     : ${restored.exactMatch ? '100% Exacte (Bit-à-bit)' : 'Inexacte'}`);
        console.log(`Sommets      : ${restored.vertices.length}`);
        console.log(`Faces        : ${restored.faces.length}`);

        const aabb = MeshAwarenessUtils.computeCollisionBox(
            restored.vertices.flatMap(v => [v.x, v.y, v.z])
        );
        console.log(`Bounding Box : Min [${aabb.min.x.toFixed(2)}, ${aabb.min.y.toFixed(2)}, ${aabb.min.z.toFixed(2)}]`);
        console.log(`             : Max [${aabb.max.x.toFixed(2)}, ${aabb.max.y.toFixed(2)}, ${aabb.max.z.toFixed(2)}]`);

        // Sauvegarde optionnelle
        const saveAnswer = await rl.question(`\nVoulez-vous sauvegarder le modèle généré au format .obj ? (O/n) [O] : `);
        if (saveAnswer.trim().toLowerCase() !== 'n') {
            const outPath = path.resolve(`generated_${targetModelId}.obj`);
            const objText = OBJExporter.stringify(restored.vertices, restored.faces, targetModelId);
            fs.writeFileSync(outPath, objText, 'utf8');
            console.log(`💾 Fichier OBJ sauvegardé : ${outPath}`);
        }

        console.log('\nTerminé avec succès.');
    } finally {
        rl.close();
    }
}

